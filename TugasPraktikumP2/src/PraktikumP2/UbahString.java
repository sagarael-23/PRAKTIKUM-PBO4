package PraktikumP2;

public class UbahString {
    public static void main(String[] args) {
        String a = "Saya Belajar Java";
        String b = "Saya Belajar Java";
        
        System.out.println("String a awal: " + a);
        System.out.println("String a menjadi huruf kecil: " + a.toLowerCase());
        
        System.out.println("\nString b awal: " + b);
        System.out.println("String b menjadi huruf besar: " + b.toUpperCase());
    }
}